def test_child_template_inherits_base_template(tmp_path):
    template_dir = tmp_path / "email"
    template_dir.mkdir()

    base_template = template_dir / "base.html"
    child_template = template_dir / "job_confirmation.html"

    base_template.write_text(
        """
        <!DOCTYPE html>
        <html>
        <body>
            <header>
                {% block header %}FieldOps{% endblock %}
            </header>

            <main>
                {% block content %}
                <h1>{% block heading %}FieldOps Notification{% endblock %}</h1>
                {% block body %}Default body{% endblock %}
                {% endblock %}
            </main>
        </body>
        </html>
        """,
        encoding="utf-8",
    )

    child_template.write_text(
        """
        {% extends "base.html" %}

        {% block heading %}
        Job Confirmation
        {% endblock %}

        {% block body %}
        Your job has been confirmed.
        {% endblock %}
        """,
        encoding="utf-8",
    )

    from jinja2 import Environment, FileSystemLoader

    env = Environment(
        loader=FileSystemLoader(str(template_dir)),
        autoescape=True,
    )

    template = env.get_template("job_confirmation.html")

    rendered = template.render()

    assert "FieldOps" in rendered
    assert "Job Confirmation" in rendered
    assert "Your job has been confirmed." in rendered
    assert "Default body" not in rendered


def test_child_template_can_override_header_and_content(tmp_path):
    template_dir = tmp_path / "email"
    template_dir.mkdir()

    (template_dir / "base.html").write_text(
        """
        <html>
        <body>
            {% block header %}FieldOps{% endblock %}

            {% block content %}
            <h1>{% block heading %}Default Heading{% endblock %}</h1>
            {% block body %}Default Body{% endblock %}
            {% endblock %}
        </body>
        </html>
        """,
        encoding="utf-8",
    )

    (template_dir / "custom.html").write_text(
        """
        {% extends "base.html" %}

        {% block header %}
        Custom Header
        {% endblock %}

        {% block heading %}
        Custom Heading
        {% endblock %}

        {% block body %}
        Custom Body
        {% endblock %}
        """,
        encoding="utf-8",
    )

    from jinja2 import Environment, FileSystemLoader

    env = Environment(
        loader=FileSystemLoader(str(template_dir)),
        autoescape=True,
    )

    rendered = env.get_template("custom.html").render()

    assert "Custom Header" in rendered
    assert "Custom Heading" in rendered
    assert "Custom Body" in rendered
    assert "FieldOps" not in rendered
    assert "Default Heading" not in rendered
    assert "Default Body" not in rendered