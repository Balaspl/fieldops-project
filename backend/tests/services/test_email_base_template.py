def test_child_template_inherits_base_layout(tmp_path):
    child_template = """
{% extends "email/base.html" %}

{% block title %}
Job Confirmation
{% endblock %}

{% block heading %}
Your Job Is Confirmed
{% endblock %}

{% block body %}
Your service job has been successfully confirmed.
{% endblock %}
"""

    child_path = tmp_path / "job_confirmation.html"
    child_path.write_text(child_template, encoding="utf-8")

    env = Environment(
        loader=FileSystemLoader(
            [
                TEMPLATE_DIR,
                tmp_path,
            ]
        ),
        autoescape=True,
    )

    html = env.get_template("job_confirmation.html").render(
        cta_url="https://example.com/job/123",
        cta_text="View Job",
    )

    # Child content
    assert "Job Confirmation" in html
    assert "Your Job Is Confirmed" in html
    assert "Your service job has been successfully confirmed." in html

    # Inherited base layout
    assert "FieldOps" in html
    assert "Generated by FieldOps" in html
    assert 'class="email-container"' in html

