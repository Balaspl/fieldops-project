from pathlib import Path
from app.services.email.template_renderer import EmailTemplateRenderer
from jinja2 import Environment, FileSystemLoader
from app.services.email.email_preview import EmailPreviewService

TEMPLATE_DIR = Path(__file__).resolve().parents[2] / "app" / "templates"


def get_environment():
    return Environment(
        loader=FileSystemLoader(TEMPLATE_DIR),
        autoescape=True,
    )


def test_base_html_template_loads():
    env = get_environment()
    template = env.get_template("email/base.html")

    assert template is not None


def test_base_text_template_loads():
    env = get_environment()
    template = env.get_template("email/base.txt")

    assert template is not None


def test_base_html_renders_branding_and_content():
    env = get_environment()

    html = env.get_template("email/base.html").render()

    assert "FieldOps" in html
    assert "FieldOps Notification" in html
    assert "Generated by FieldOps" in html


def test_base_html_renders_dynamic_values():
    env = get_environment()

    html = env.get_template("email/base.html").render(
        logo_url="https://example.com/logo.png",
        cta_url="https://example.com/job/123",
        cta_text="View Job",
        support_email="support@fieldops.io",
        unsubscribe_url="https://example.com/unsubscribe",
    )

    assert "https://example.com/logo.png" in html
    assert "https://example.com/job/123" in html
    assert "View Job" in html
    assert "support@fieldops.io" in html
    assert "https://example.com/unsubscribe" in html


