/**
 * Returns a local, category-specific image for a diagnostic issue card.
 * `index` is the issue's position in the selected category's taxonomy list.
 */
export const getUniqueIssueCardImage = (
  issueTitle: string,
  categoryId: string,
  serviceTypeId: string,
  index: number = 0
): string => {
  const categoryFiles = ISSUE_IMAGE_FILES_BY_CATEGORY[serviceTypeId]?.[categoryId];

  const fallbackPool = ISSUE_TRADE_POOLS[serviceTypeId] || DEFAULT_ISSUE_POOL;

  if (categoryFiles?.length) {
    if (index >= 0 && index < categoryFiles.length) {
      return categoryFiles[index];
    }

    // Some existing Plumbing and Carpentry folders have fewer files than
    // the number of issues in the taxonomy. Use a distinct trade fallback
    // for only those uncovered positions rather than reusing a local image.
    const fallbackIndex = Math.max(0, index - categoryFiles.length) % fallbackPool.length;
    return fallbackPool[fallbackIndex];
  }

  // Electrical categories without dedicated issue-image folders use this fallback.
  return fallbackPool[Math.abs(index) % fallbackPool.length];
};

export const getIssueCardImage = getUniqueIssueCardImage;
